# the whole stage against a flagged crate


@pytest.fixture
def crate_env(tmp_path, click_track):
    """Three 30 fps clips, flagged ranges 0.5-5.5s, ratings 5, 4, 3."""
    cfg = dict(config.DEFAULTS)
    cfg.update({"work_dir": str(tmp_path / "work")})
    con = db.connect(cfg)
    src = tmp_path / "src" / "DELTA REEL"
    src.mkdir(parents=True)
    for i in range(3):
        p = src / f"clip{i + 1}.mp4"
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-f", "lavfi", "-i",
                        "testsrc2=size=320x180:rate=30:duration=6",
                        "-pix_fmt", "yuv420p", str(p)], check=True)
        cur = con.execute("INSERT INTO media (src_path,event,bytes,state) "
                          "VALUES (?,?,0,'proxied')", (str(p), "DELTA REEL"))
        con.execute("INSERT INTO clips (media_id,start,end,state,score,flagged,"
                    "my_rating) VALUES (?,?,?,'scored',?,1,?)",
                    (cur.lastrowid, 0.5, 5.5, 8 - i, 5 - i))
    con.commit()
    yield cfg, con, click_track
    con.close()


def test_edl_events_and_timecodes(crate_env):
    """bpm=120, offset=0, bars=2 -> 4.0s segments; an 8s track -> 2 events.

    Sources run at 30 fps and the sequence at 24, so src and rec timecodes are
    computed on different frame rates - which is exactly the probe_fps path.
    """
    cfg, con, track = crate_env
    out = Path(cfg["work_dir"]) / "assemble.edl"
    assemble.run(cfg, con, ns(track=str(track), bpm=120, offset=0.0,
                              bars=2, fps=24, out=str(out)))
    lines = [l for l in out.read_text().splitlines() if l and l[0].isdigit()]
    assert len(lines) == 2
    # event 1 takes clip1 (highest rating): src 0.5-4.5s at 30fps, rec 0-4s
    assert lines[0].startswith("001  CLIP1")
    assert "00:00:00:15 00:00:04:15 00:00:00:00 00:00:04:00" in lines[0]
    # event 2 takes clip2, the record timeline continues at 4-8s
    assert lines[1].startswith("002  CLIP2")
    assert "00:00:00:15 00:00:04:15 00:00:04:00 00:00:08:00" in lines[1]


def test_edl_uses_original_filenames_for_relink(crate_env):
    cfg, con, track = crate_env
    out = Path(cfg["work_dir"]) / "assemble.edl"
    assemble.run(cfg, con, ns(track=str(track), bpm=120, offset=0.0,
                              bars=2, fps=24, out=str(out)))
    text = out.read_text()
    assert "* FROM CLIP NAME: clip1.mp4" in text
    assert "* FROM CLIP NAME: clip2.mp4" in text


def test_stops_when_clips_run_out(tmp_path, click_track, capsys):
    """One clip covers the first segment only; stop, never loop or reuse."""
    cfg = dict(config.DEFAULTS)
    cfg.update({"work_dir": str(tmp_path / "work")})
    con = db.connect(cfg)
    p = tmp_path / "only.mp4"
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-f", "lavfi", "-i",
                    "testsrc2=size=320x180:rate=24:duration=6",
                    "-pix_fmt", "yuv420p", str(p)], check=True)
    cur = con.execute("INSERT INTO media (src_path,event,bytes,state) "
                      "VALUES (?,?,0,'proxied')", (str(p), "EVENT"))
    con.execute("INSERT INTO clips (media_id,start,end,state,score,flagged,"
                "my_rating) VALUES (?,?,?,'scored',7,1,4)",
                (cur.lastrowid, 0.0, 6.0))
    con.commit()
    out = Path(cfg["work_dir"]) / "assemble.edl"
    assemble.run(cfg, con, ns(track=str(click_track), bpm=120, offset=0.0,
                              bars=2, fps=24, out=str(out)))
    lines = [l for l in out.read_text().splitlines() if l and l[0].isdigit()]
    assert len(lines) == 1
    assert "uncovered" in capsys.readouterr().out
    assert "00:00:04:00" in lines[0], "one 4s event, then the EDL stops"


def test_skips_cloud_only_originals(crate_env, monkeypatch, capsys):
    """A placeholder passes exists(), so the cloud check must do the work."""
    from savvy import storage
    cfg, con, track = crate_env
    monkeypatch.setattr(storage, "is_cloud_only_path", lambda p: True)
    with pytest.raises(SystemExit):
        assemble.run(cfg, con, ns(track=str(track), bpm=120, offset=0.0,
                                  bars=2, fps=24, out="unused.edl"))
    assert "online-only" in capsys.readouterr().out


