# EDL writer


def test_write_cmx3600_uses_source_and_sequence_fps(tmp_path):
    """src timecodes are at the original's 30 fps, record at the 24 fps cut."""
    ev = edl.Event(reel="CLIP1", source_path=Path("/x/CLIP1.mp4"),
                   src_in=0.5, src_out=4.5, rec_in=0.0, rec_out=4.0, src_fps=30)
    out = tmp_path / "a.edl"
    edl.write_cmx3600([ev], 24.0, out)
    text = out.read_text()
    assert text.startswith("TITLE: A\nFCM: NON-DROP FRAME")
    assert "00:00:00:15 00:00:04:15 00:00:00:00 00:00:04:00" in text
    assert "* FROM CLIP NAME: CLIP1.mp4" in text

