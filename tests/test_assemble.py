"""`savvy assemble` against synthetic audio and footage. No API key, no network.

Same pattern as test_pipeline.py: everything is generated by ffmpeg at test
time. A click track exercises the BPM estimator; a tagged copy exercises the
tag path; a small flagged crate exercises the EDL writer against
hand-calculated timecodes.
"""
import argparse
import subprocess
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from savvy import beatgrid, config, db, edl, media  # noqa: E402
from savvy.stages import assemble  # noqa: E402


def ns(**kw):
    return argparse.Namespace(**kw)


# --------------------------------------------------------------------------
# synthetic click track and the estimators


@pytest.fixture(scope="session")
def click_track(tmp_path_factory):
    """8s of 1000 Hz beeps at 120 BPM - one ~0.13s beep every 0.5s.

    aevalsrc multiplies a 1000 Hz sine by a 2 Hz square gate, so the period is
    0.5s and the first beep lands at t=0. No tags, which is what makes this
    exercise the estimator.
    """
    d = tmp_path_factory.mktemp("track")
    p = d / "click.wav"
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-f", "lavfi", "-i",
                    r"aevalsrc=sin(2*PI*1000*t)*gt(sin(2*PI*t/0.5)\,0.7)"
                    ":d=8:s=11025", str(p)], check=True)
    return p


def test_detect_bpm_estimates_click_track(click_track):
    bpm, src = beatgrid.detect_bpm(click_track)
    assert src == "estimated", "a synthetic wav has no tag"
    assert abs(bpm - 120) <= 5


def test_detect_offset_finds_first_beat(click_track):
    offset, src = beatgrid.detect_offset(click_track, 120)
    assert src == "estimated"
    assert abs(offset) < 0.5, "the first beep lands at t=0"


def test_override_beats_tag_and_estimate(click_track):
    assert beatgrid.detect_bpm(click_track, override=140) == (140.0, "override")
    assert beatgrid.detect_offset(click_track, 120, override=1.5) == (1.5, "override")


def test_detect_bpm_prefers_tag_over_estimate(click_track, tmp_path):
    """A DJ tool's tag wins - that is the whole point of the priority order."""
    mp3 = tmp_path / "tagged.mp3"
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(click_track),
                    "-b:a", "96k", str(mp3)], check=True)
    from mutagen.id3 import ID3, TBPM
    tags = ID3(mp3)
    tags.add(TBPM(encoding=3, text=["123"]))
    tags.save(mp3)
    bpm, src = beatgrid.detect_bpm(mp3)
    assert src == "tag"
    assert bpm == 123.0


def test_beat_grid_spacing():
    grid = beatgrid.beat_grid(120, 0.0, 4.0)
    assert grid == [0.0, 0.5, 1.0, 1.5, 2.0, 2.5, 3.0, 3.5, 4.0]


